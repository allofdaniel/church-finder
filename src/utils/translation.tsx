// ============= ROMANIZATION (Korean → English) =============
const CHOSUNG_ROM = ['g', 'kk', 'n', 'd', 'tt', 'r', 'm', 'b', 'pp', 's', 'ss', '', 'j', 'jj', 'ch', 'k', 't', 'p', 'h']
const JUNGSUNG_ROM = ['a', 'ae', 'ya', 'yae', 'eo', 'e', 'yeo', 'ye', 'o', 'wa', 'wae', 'oe', 'yo', 'u', 'wo', 'we', 'wi', 'yu', 'eu', 'ui', 'i']
const JONGSUNG_ROM = ['', 'k', 'k', 'k', 'n', 'n', 'n', 't', 'l', 'l', 'l', 'l', 'l', 'l', 'l', 'l', 'm', 'p', 'p', 't', 't', 'ng', 't', 't', 'k', 't', 'p', 't']

export function romanize(text: string): string {
  let result = ''
  for (const char of text) {
    const code = char.charCodeAt(0)
    if (code >= 0xAC00 && code <= 0xD7A3) {
      const syllable = code - 0xAC00
      const cho = Math.floor(syllable / 588)
      const jung = Math.floor((syllable % 588) / 28)
      const jong = syllable % 28
      result += CHOSUNG_ROM[cho] + JUNGSUNG_ROM[jung] + JONGSUNG_ROM[jong]
    } else {
      result += char
    }
  }
  return result.replace(/\b\w/g, c => c.toUpperCase())
}

