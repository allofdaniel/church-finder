// ============= TEXT TRANSLATION =============
export function translateText(text: string, mapping: Record<string, string>): string {
  if (!text || Object.keys(mapping).length === 0) return text
  let result = text
  const sortedKeys = Object.keys(mapping).sort((a, b) => b.length - a.length)
  for (const key of sortedKeys) {
    result = result.replace(new RegExp(key, 'g'), mapping[key])
  }
  return result
}

// ============= CHOSUNG (Initial Consonant) =============
const CHOSUNG = ['ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ']

export function getChosung(str: string): string {
  let result = ''
  for (const char of str) {
    const code = char.charCodeAt(0)
    if (code >= 0xAC00 && code <= 0xD7A3) {
      const cho = Math.floor((code - 0xAC00) / 588)
      result += CHOSUNG[cho]
    }
  }
  return result
}

// ============= KEYWORD HIGHLIGHTING =============
export function highlightKeyword(text: string, query: string): ReactNode {
  if (!query) return text
  const idx = text.toLowerCase().indexOf(query.toLowerCase())
  if (idx === -1) return text
  return (
    <>
      {text.slice(0, idx)}
      <mark>{text.slice(idx, idx + query.length)}</mark>
      {text.slice(idx + query.length)}
    </>
  )
}

// ============= DISTRICT EXTRACTION =============
export function extractDistrict(address: string): string[] {
  const districts: string[] = []
  // 시/군/구 추출
  const sigunguMatch = address.match(/([가-힣]+[시군구])/g)
  if (sigunguMatch) {
    districts.push(...sigunguMatch)
  }
  // 동/읍/면/리 추출
  const dongMatch = address.match(/([가-힣]+[동읍면리])/g)
  if (dongMatch) {
    districts.push(...dongMatch)
  }
  return districts
}
